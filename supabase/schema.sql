-- Closar database on Supabase (Postgres). Same tables and columns as the old data/closar.db.
-- The laptop connects with the database connection string (full access).
-- The studio page on GitHub Pages connects with the public anon key + your login, and the rules
-- at the bottom let ONLY accounts listed in `owners` read or change anything.

create table if not exists posts (
  id text primary key,
  source text, platform text, url text, author text, title text, text text,
  posted_at text, found_at text,
  dm_url text, reply_hint text,
  stage text default 'queued',
  guess text,
  verdict text, score integer, category text, budget text, flags text, why text,
  draft text, reply_via text,
  outreach text default 'todo',
  sent_at text, note text,
  kind text default 'hire', service text, mention text, mention_used integer default 0, contact_id bigint
);
create index if not exists posts_view on posts (kind, stage, verdict, outreach);
create index if not exists posts_url on posts (url);

create table if not exists state (k text primary key, v text);

create table if not exists upwork_jobs (
  id text primary key, ciphertext text, url text, title text, description text, skills text,
  budget text, experience text, applicants integer, client text,
  posted_at text, found_at text, query text,
  stage text default 'queued',
  verdict text, score integer, category text, why text, flags text, bid text, proposal text,
  questions text, answers text,
  status text default 'todo',
  applied_at text
);

create table if not exists contacts (
  id bigint generated by default as identity primary key,
  service text, source text, source_ref text,
  dedupe_key text unique,
  name text, handle text, platform text, profile_url text, website text, email text,
  evidence text, evidence_url text,
  stage text default 'cold',
  score integer, why text, flags text,
  contact_via text, dm_url text,
  dm_draft text, email_subject text, email_body text, followup_draft text,
  value double precision, currency text, note text,
  scored integer default 0,
  follow_ups integer default 0, next_follow_up text, last_contact_at text,
  created_at text, updated_at text,
  audit text, main_area text, audited_at text, kind text
);

create table if not exists events (
  id bigint generated by default as identity primary key,
  contact_id bigint, at text, kind text, channel text, text text
);
create index if not exists events_contact on events (contact_id);

-- ---------- who may use the studio from the web ----------
create table if not exists owners (uid uuid primary key);

create or replace function is_owner() returns boolean
language sql stable security definer set search_path = public as
$$ select exists (select 1 from owners where uid = auth.uid()) $$;

alter table posts       enable row level security;
alter table state       enable row level security;
alter table upwork_jobs enable row level security;
alter table contacts    enable row level security;
alter table events      enable row level security;
alter table owners      enable row level security;   -- no policy: invisible from the web

drop policy if exists owner_all on posts;
drop policy if exists owner_all on state;
drop policy if exists owner_all on contacts;
drop policy if exists owner_all on events;
create policy owner_all on posts    for all to authenticated using (is_owner()) with check (is_owner());
create policy owner_all on state    for all to authenticated using (is_owner()) with check (is_owner());
create policy owner_all on contacts for all to authenticated using (is_owner()) with check (is_owner());
create policy owner_all on events   for all to authenticated using (is_owner()) with check (is_owner());
